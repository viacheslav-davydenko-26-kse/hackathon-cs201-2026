/**
 * @param {keyof typeof PATHS} name
 * @param {string} [cls]   додатковий клас (наприклад, 'icon--lg')
 * @returns {SVGSVGElement}
 */
export function icon(name, cls = '') {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', `icon ${cls}`.trim());
  svg.innerHTML = PATHS[name] ?? ''; // статичні рядки з цього файлу, не дані користувача
  if (!PATHS[name]) console.warn('icon: unknown', name);
  return svg;
}

/** Замінює всі <i data-icon="name" class="..."> у root на SVG-іконки. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    el.replaceWith(icon(el.dataset.icon, el.className));
  });
}
